export default function Header() {
  const [isScrolled, setIsScrolled] = useState(false);
  const [isMenuOpen, setIsMenuOpen] = useState(false);
  const pathname = usePathname();
  const isHome = pathname === "/";

  useEffect(() => {
    const handleScroll = () => {
      setIsScrolled(window.scrollY > 50);
    };
    window.addEventListener("scroll", handleScroll, { passive: true });
    return () => window.removeEventListener("scroll", handleScroll);
  }, []);

  useEffect(() => {
    if (isMenuOpen) {
      document.body.style.overflow = "hidden";
    } else {
      document.body.style.overflow = "";
    }
    return () => {
      document.body.style.overflow = "";
    };
  }, [isMenuOpen]);

  // Determine text color based on page and scroll state
  const textColor = !isHome || isScrolled ? "text-brand-navy" : "text-white";
  const textHover = !isHome || isScrolled ? "hover:text-brand-teal" : "hover:text-white/80";
  const pillBg = !isHome || isScrolled
    ? "bg-white shadow-lg"
    : "bg-brand-navy/30 backdrop-blur-md";

  return (
    <header
      className={cn(
        "fixed left-0 right-0 top-0 z-50 flex justify-center px-4 py-4 transition-all duration-500",
        (!isHome || isScrolled) && "bg-white/90 shadow-lg backdrop-blur-xl"
      )}
    >
      <div
        className={cn(
          "flex w-full max-w-7xl items-center justify-between rounded-full px-6 py-3 transition-all duration-500",
          pillBg
        )}
      >
        {/* Logo */}
        <Link href="/" className="flex-shrink-0">
          <Image
            src="/images/logos/Exec-Air_Logo_2023.png"
            alt="Exec-Air Air Conditioning"
            width={200}
            height={60}
            className="h-12 w-auto md:h-14"
            priority
          />
        </Link>

        {/* Desktop Nav */}
        <nav className="hidden items-center gap-1 lg:flex">
          {navLinks.map((link) => {
            const isActive = pathname === link.href;
            return (
              <Link
                key={link.name}
                href={link.href}
                className={cn(
                  "rounded-full px-4 py-2 text-sm font-medium uppercase tracking-wider transition-all duration-300",
                  isActive
                    ? "bg-brand-teal/10 text-brand-teal"
                    : cn(textColor, textHover)
                )}
              >
                {link.name}
              </Link>
            );
          })}
        </nav>

        {/* Desktop Social Icons */}
        <div className="hidden items-center gap-1 lg:flex">
          {socialLinks.map((social) => (
            <a
              key={social.name}
              href={social.href}
              target="_blank"
              rel="noopener noreferrer"
              aria-label={social.name}
              className={cn(
                "rounded-full p-2 transition-all duration-300 hover:scale-110",
                textColor === "text-white"
                  ? "text-white/60 hover:bg-white/10 hover:text-white"
                  : "text-brand-navy/50 hover:bg-brand-teal/10 hover:text-brand-teal"
              )}
            >
              {social.icon}
            </a>
          ))}
        </div>

        {/* Mobile Hamburger */}
        <button
          onClick={() => setIsMenuOpen(!isMenuOpen)}
          aria-label="Toggle menu"
          className={cn(
            "rounded-full p-2 transition-colors lg:hidden",
            textColor
          )}
        >
          {isMenuOpen ? <X className="h-6 w-6" /> : <Menu className="h-6 w-6" />}
        </button>
      </div>

      {/* Mobile Menu Dropdown */}
      {isMenuOpen && (
        <div className="absolute left-4 right-4 top-full mt-2 rounded-3xl bg-white p-6 shadow-2xl lg:hidden">
          <nav className="flex flex-col gap-3">
            {navLinks.map((link) => {
              const isActive = pathname === link.href;
              return (
                <Link
                  key={link.name}
                  href={link.href}
                  onClick={() => setIsMenuOpen(false)}
                  className={cn(
                    "rounded-xl px-4 py-3 text-lg font-medium uppercase tracking-wider transition-colors",
                    isActive
                      ? "bg-brand-teal/10 text-brand-teal"
                      : "text-brand-navy hover:bg-brand-sky/20 hover:text-brand-teal"
                  )}
                >
                  {link.name}
                </Link>
              );
            })}
          </nav>
          <div className="mt-6 flex justify-center gap-4 border-t border-gray-100 pt-6">
            {socialLinks.map((social) => (
              <a
                key={social.name}
                href={social.href}
                target="_blank"
                rel="noopener noreferrer"
                aria-label={social.name}
                className="rounded-full p-3 text-brand-navy/50 transition-all hover:bg-brand-teal/10 hover:text-brand-teal"
              >
                {social.icon}
              </a>
            ))}
          </div>
        </div>
      )}
    </header>
  );
}
